/* rof_hiscore_factory.h — the FACTORY-FRESH high-score block for $3700-$37C7.
 *
 * The high-score table + initials entry runs on a 256-byte block that the disk game read from
 * sectors $02CE/$02CF; both SIO calls are NOPped out of rof.xex, so the block has to be supplied
 * by the port.  See docs/high-score-initials.md (why) and docs/high-score-restore-plan.md (how).
 *
 * PROVENANCE — these are the original bytes, not a reconstruction:
 *   • Lifted from the Atari 8-bit 64 KB cartridge release (v5.0), which has no disk to read and so
 *     carries the table in ROM, at cart-image offset $6200.
 *   • Cross-verified byte-identical against a v4.1 DISK image (ATR, factory block at file offset
 *     $03218 = sector 101): the mode-7 heading row, the column-header row and every entry row that
 *     that disk's owner had not overwritten (FOX / LOREN / DRAGON) match exactly.  The disk copy
 *     had COLBEAR/LARRY/LORD played into it, so the cart copy is the pristine one.
 *
 * Layout: 20-byte rows, cell = (ANTIC internal char in bits 0-5) | (colour register in bits 6-7).
 * Row 0 is ANTIC mode 7 (double height), rows 1-9 are mode 6.  Entry rows carry the name at
 * offsets 0-7, the level at 9-10 and the score right-aligned in 12-19.
 *
 * ⚠ THE SIGNATURE IS NOT IN HERE, DELIBERATELY.  validate_save_state $5D0D compares $37C8-$37ED
 * against mem[$7BDB..] — and the builds disagree on it: this disk's block says "Copyright (c) 1985
 * Lucasfilm Ltd. v4.1" while our rof.xex holds "XCopyright (c) 1987 Lucasfilm Ltd. v4.1" at $7BDA.
 * Hardcoding either string would fail the check against the other build, so copy 38 bytes from
 * mem[$7BDA + 1] at load time instead.  Also set $37EE (level_progress) = $10.
 */
